import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve, sep } from 'node:path';

import { GetObjectCommand, PutObjectCommand, S3Client } from '@aws-sdk/client-s3';
import { getSignedUrl } from '@aws-sdk/s3-request-presigner';

import type { OrderConfig } from '../config/index.js';

export interface StoredObject {
  key: string;
  body: Buffer;
  contentType: string;
  /** Download file name (Content-Disposition). */
  fileName: string;
  sha256: string;
}

/**
 * Private document storage (invoices). Objects are NEVER public: downloads go through short-lived
 * signed URLs (Spaces) or are streamed by the API after an ownership check (local).
 */
export interface ObjectStore {
  readonly kind: 'spaces' | 'local';
  put(object: StoredObject): Promise<void>;
  /** Signed GET URL valid for `ttlSeconds`; null when the store cannot sign (local). */
  signedUrl(key: string, fileName: string, ttlSeconds: number): Promise<string | null>;
  /** Raw bytes (local streaming, tests). */
  get(key: string): Promise<Buffer>;
}

/** DigitalOcean Spaces (S3 API) with ACL private and no-store caching. */
export class SpacesObjectStore implements ObjectStore {
  readonly kind = 'spaces';
  private readonly s3: S3Client;
  private readonly bucket: string;

  constructor(config: OrderConfig) {
    this.bucket = config.AWS_BUCKET_NAME ?? '';
    this.s3 = new S3Client({
      endpoint: config.AWS_ENDPOINT,
      region: config.AWS_REGION,
      forcePathStyle: false,
      credentials: {
        accessKeyId: config.AWS_ACCESS_KEY_ID ?? '',
        secretAccessKey: config.AWS_SECRET_ACCESS_KEY ?? '',
      },
    });
  }

  async put(o: StoredObject): Promise<void> {
    await this.s3.send(
      new PutObjectCommand({
        Bucket: this.bucket,
        Key: o.key,
        Body: o.body,
        ACL: 'private',
        ContentType: o.contentType,
        ContentDisposition: `attachment; filename="${o.fileName}"`,
        CacheControl: 'private, no-store',
        Metadata: { sha256: o.sha256 },
      }),
    );
  }

  signedUrl(key: string, fileName: string, ttlSeconds: number): Promise<string> {
    return getSignedUrl(
      this.s3,
      new GetObjectCommand({
        Bucket: this.bucket,
        Key: key,
        ResponseContentDisposition: `attachment; filename="${fileName}"`,
        ResponseContentType: 'application/pdf',
      }),
      { expiresIn: ttlSeconds },
    );
  }

  async get(key: string): Promise<Buffer> {
    const res = await this.s3.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }));
    return Buffer.from(
      await (res.Body as { transformToByteArray(): Promise<Uint8Array> }).transformToByteArray(),
    );
  }
}

/** DEV / TEST ONLY: files under a directory (config refuses `local` in prod). */
export class LocalObjectStore implements ObjectStore {
  readonly kind = 'local';
  private readonly root: string;

  constructor(dir: string) {
    this.root = resolve(dir);
  }

  async put(o: StoredObject): Promise<void> {
    const path = this.path(o.key);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, o.body);
  }

  signedUrl(): Promise<null> {
    return Promise.resolve(null);
  }

  get(key: string): Promise<Buffer> {
    return readFile(this.path(key));
  }

  /** Keys are generated by us, but never let one escape the root. */
  private path(key: string): string {
    const path = resolve(this.root, key);
    if (!path.startsWith(this.root + sep)) throw new Error(`invalid object key ${key}`);
    return path;
  }
}

export const buildObjectStore = (config: OrderConfig): ObjectStore =>
  config.INVOICE_STORAGE === 'spaces'
    ? new SpacesObjectStore(config)
    : new LocalObjectStore(config.INVOICE_LOCAL_DIR);
